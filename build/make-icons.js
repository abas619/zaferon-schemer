/** Lucide files are a single <svg> wrapper; keep only the drawing inside. */
function innerOf(name) {
  const file = path.join(SRC_DIR, `${name}.svg`);
  if (!fs.existsSync(file)) throw new Error(`lucide-static has no icon named "${name}"`);
  const raw = fs.readFileSync(file, 'utf8');
  const open = raw.indexOf('>', raw.indexOf('<svg'));
  const close = raw.lastIndexOf('</svg>');
  if (open < 0 || close < 0) throw new Error(`could not parse ${name}.svg`);
  return raw
    .slice(open + 1, close)
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .trim();
}

function build() {
  const names = [...new Set(ICONS)].sort();
  const rows = names.map((n) => `    ${JSON.stringify(n)}: '${innerOf(n).replace(/'/g, "\\'")}'`);

  const js = `/* ==================================================================
 * Icon set — AUTO-GENERATED by build/make-icons.js, do not edit.
 *
 * Lucide (ISC), 24x24, stroked with currentColor so every icon follows the
 * theme for free. Regenerate with \`npm run icons\`.
 * ================================================================== */
(function () {
  'use strict';

  const CS = (window.CS = window.CS || {});

  const PATHS = {
${rows.join(',\n')}
  };

  const DEFAULT_STROKE = 1.75;

  /**
   * Markup for one icon.
   * @param {string} name    key in PATHS
   * @param {number} [size]  square size in CSS px
   * @param {{stroke?:number, cls?:string}} [opts]
   */
  function svg(name, size, opts) {
    const d = PATHS[name];
    if (!d) return '';
    const s = size || 16;
    const o = opts || {};
    const w = o.stroke == null ? DEFAULT_STROKE : o.stroke;
    const cls = 'icon' + (o.cls ? ' ' + o.cls : '');
    return (
      '<svg class="' + cls + '" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" ' +
      'fill="none" stroke="currentColor" stroke-width="' + w + '" ' +
      'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' +
      d + '</svg>'
    );
  }

  /** A live <svg> element, for callers that need a node rather than markup. */
  function node(name, size, opts) {
    const wrap = document.createElement('span');
    wrap.innerHTML = svg(name, size, opts);
    return wrap.firstChild;
  }

  /** Swap an existing element's icon without rebuilding it. */
  function set(target, name, size, opts) {
    if (target) target.innerHTML = svg(name, size, opts);
    return target;
  }

  CS.Icons = { svg, node, set, has: (n) => !!PATHS[n], names: Object.keys(PATHS) };
})();
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, js);
  process.stdout.write(`wrote ${path.relative(ROOT, OUT)} — ${names.length} icons, ${js.length} bytes\n`);
}

build();
