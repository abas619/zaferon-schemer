'use strict';

/**
 * Generates src/js/ui/icons.js from lucide-static.
 *
 *   npm run icons
 *
 * The renderer has no bundler and a `script-src 'self' file:` CSP, so Lucide
 * cannot be pulled in at runtime — the handful of icons the app actually uses
 * are inlined here instead. Deterministic: re-running produces a byte-identical
 * file, so a diff only ever means the icon list changed.
 *
 * Adding an icon: add its lucide name to ICONS below and re-run.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'node_modules', 'lucide-static', 'icons');
const OUT = path.join(ROOT, 'src', 'js', 'ui', 'icons.js');

